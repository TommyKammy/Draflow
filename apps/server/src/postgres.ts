import { createRequire } from 'node:module';
import { createHash, randomUUID } from 'node:crypto';
import { AsyncLocalStorage } from 'node:async_hooks';
import { MessageChannel, Worker, receiveMessageOnPort } from 'node:worker_threads';
import { ledgerTables, temporaryWebhookTable } from './ledger-schema.js';

export interface SharedOptions {
  connectionString: string;
  organization: string;
  leaseMs?: number;
  pollMs?: number;
  role?: 'all' | 'worker' | 'intake' | 'scheduler';
  maxActiveRuns?: number;
  maxTargetRequests?: number;
  // Map an organization-local credential ID to a shared upstream rate-limit account.
  rateAccounts?: Record<string, string>;
}
type Value = number | string | null;
type Result = { rows: Record<string, Value>[]; changes: number; error?: string };
export function validateOrganization(id: string) {
  if (
    typeof id !== 'string' ||
    !id ||
    Buffer.byteLength(id) > 256 ||
    id.includes('\0') ||
    Buffer.from(id).toString('utf8') !== id
  )
    throw Error('Expected a valid organization ID');
}
export class OwnershipLost extends Error {}

// SQL here is exclusively internal ledger SQL. Preserve its public camel-case
// projections, and leave JSON paths and literal business values untouched.
function identifiers(sql: string) {
  return sql.replace(/'(?:''|[^'])*'|\b[A-Za-z_]\w*\b/g, (word) =>
    !word.startsWith("'") && (/[a-z][A-Z]/.test(word) || word === 'offset') ? '"' + word + '"' : word,
  );
}
const upserts: Record<string, [string, string[]]> = {
  readyAfter: ['runId', ['cutoff']],
  deliveries: ['workflowId,triggerNodeId,eventKey,source', ['expiresAt', 'runId', 'rowid']],
  history: ['workflowId,id', ['status', 'startedAt', 'summary', 'detail', 'rowid']],
  continuations: ['runId', ['checkpoint', 'token', 'mode', 'dueAt', 'response']],
};
function querySql(sql: string) {
  if (/INSERT OR IGNORE/i.test(sql))
    sql = sql.replace('INSERT OR IGNORE', 'INSERT') + ' ON CONFLICT DO NOTHING';
  const replace = sql.match(/INSERT OR REPLACE INTO (\w+)/);
  if (replace) {
    const [keys, cols] = upserts[replace[1]!]!;
    sql =
      sql.replace('INSERT OR REPLACE', 'INSERT') +
      ' ON CONFLICT (' +
      keys +
      ') DO UPDATE SET ' +
      cols.map((c) => c + '=excluded.' + c).join(',');
  }
  sql = sql
    .replaceAll('? IS NULL', '?::text IS NULL')
    .replaceAll('max(untilMs,excluded.untilMs)', 'greatest(rateLimits.untilMs,excluded.untilMs)')
    .replace("json_extract(checkpoint,'$.stack[0].nodeId')", "checkpoint::jsonb #>> '{stack,0,nodeId}'");
  let n = 0;
  return identifiers(sql).replace(/\?/g, () => '$' + ++n);
}

const triggers = `
CREATE OR REPLACE FUNCTION apply_effect() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.state='success' THEN
  UPDATE compensationSteps SET result=NEW.result WHERE source=NEW.key;
  INSERT INTO syncVersions SELECT scope,entity,version FROM syncWork WHERE child=NEW.runId AND item=NEW.item
    ON CONFLICT(scope,entity) DO UPDATE SET version=greatest(syncVersions.version,excluded.version);
 END IF;
 RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER apply_effect AFTER UPDATE OF state ON effects FOR EACH ROW EXECUTE FUNCTION apply_effect();
CREATE OR REPLACE FUNCTION release_work() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.data IS NOT NULL AND NEW.data IS NULL AND NEW.attempt IS NULL THEN
  DELETE FROM syncWork WHERE child=OLD.child OR child IN
    (SELECT part->>'child' FROM jsonb_array_elements(OLD.data::jsonb->'wave') AS part);
 END IF;
 RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER release_work AFTER UPDATE OF data ON recoveryPoints FOR EACH ROW EXECUTE FUNCTION release_work();`;

const orderedTables = new Set([
  'runs',
  'calls',
  'syncQueue',
  'history',
  'effects',
  'transitions',
  'compensationSteps',
  'recoveryPoints',
  'pageRuns',
  'deliveries',
]);
const schemaSql = ledgerTables
  .replace(temporaryWebhookTable, '')
  .replace(/CREATE TABLE IF NOT EXISTS (\w+) \(([\s\S]*?)\);/g, (all, name, body) =>
    orderedTables.has(name)
      ? 'CREATE TABLE IF NOT EXISTS ' +
        name +
        ' (' +
        body +
        ', rowid bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE);'
      : all,
  )
  .replace(/\bINTEGER\b/g, 'BIGINT')
  .replace(/\bREAL\b/g, 'DOUBLE PRECISION');
const nowMs = 'floor(extract(epoch from clock_timestamp())*1000)::bigint';

export class PostgresDatabase {
  readonly owner = randomUUID();
  readonly leaseMs: number;
  readonly schema: string;
  readonly lease = new AsyncLocalStorage<{ id: string; generation: number }>();
  readonly #port;
  readonly #worker;
  readonly #signal = new Int32Array(new SharedArrayBuffer(4));
  #transaction = false;
  #closed = false;
  onDisconnect?: () => void;
  constructor(readonly options: SharedOptions) {
    if (typeof options.connectionString !== 'string' || !options.connectionString)
      throw Error('Expected a PostgreSQL connection string');
    try {
      createRequire(import.meta.url).resolve('pg');
    } catch {
      throw Error('Shared mode requires the optional pg driver');
    }
    if (
      options.rateAccounts !== undefined &&
      (!options.rateAccounts ||
        typeof options.rateAccounts !== 'object' ||
        Array.isArray(options.rateAccounts) ||
        Object.values(options.rateAccounts).some((value) => typeof value !== 'string' || !value.trim()))
    )
      throw Error('Invalid shared rate account mapping');
    validateOrganization(options.organization);
    this.schema = 'df_' + createHash('sha256').update(options.organization).digest('hex').slice(0, 56);
    this.leaseMs = options.leaseMs ?? 15000;
    if (!Number.isSafeInteger(this.leaseMs) || this.leaseMs < 500) throw Error('Invalid lease interval');
    for (const value of [options.maxActiveRuns ?? 32, options.pollMs ?? 250, options.maxTargetRequests ?? 4])
      if (!Number.isSafeInteger(value) || value < 1) throw Error('Invalid shared worker limit');
    if (options.role && !['all', 'intake', 'scheduler', 'worker'].includes(options.role))
      throw Error('Invalid shared role');
    const channel = new MessageChannel();
    this.#port = channel.port1;
    this.#worker = new Worker(new URL('./pg-worker.js', import.meta.url), {
      workerData: { url: options.connectionString, port: channel.port2, signal: this.#signal.buffer },
      transferList: [channel.port2],
    });
    const disconnected = () => {
      if (!this.#closed) this.onDisconnect?.();
    };
    this.#worker.on('message', disconnected);
    this.#worker.once('error', disconnected);
    this.#worker.once('exit', disconnected);
    try {
      this.begin();
      this.raw("SELECT pg_advisory_xact_lock(hashtextextended('draflow:bootstrap',0))");
      if (!this.raw("SELECT to_regclass('draflow_coord.permits') AS t").rows[0]?.t)
        this.raw(`CREATE SCHEMA IF NOT EXISTS draflow_coord;
        CREATE TABLE IF NOT EXISTS draflow_coord.targets(target text PRIMARY KEY, until_ms bigint NOT NULL, capacity integer NOT NULL);
        CREATE TABLE IF NOT EXISTS draflow_coord.permits(token text PRIMARY KEY, target text NOT NULL REFERENCES draflow_coord.targets, owner text NOT NULL, expires bigint NOT NULL, run_id text NOT NULL, generation bigint NOT NULL);
        CREATE INDEX IF NOT EXISTS permits_target ON draflow_coord.permits(target,expires);`);
      this.raw('CREATE SCHEMA IF NOT EXISTS ' + this.schema);
      this.raw('SET search_path TO ' + this.schema + ',pg_catalog');
      if (
        !this.raw('SELECT to_regclass($1) AS present', [this.schema + '.ledger_version']).rows[0]?.present
      ) {
        this.raw(
          identifiers(
            schemaSql +
              triggers +
              `
          ALTER TABLE compensationSteps ADD FOREIGN KEY(root) REFERENCES runs(runId),
            ADD FOREIGN KEY(child) REFERENCES runs(runId),
            ADD FOREIGN KEY(workflow,revision) REFERENCES publications(workflowId,revision);
          ALTER TABLE compensations ADD FOREIGN KEY(root) REFERENCES runs(runId);
          ALTER TABLE compensationRetries ADD FOREIGN KEY(root) REFERENCES compensations(root);
          ALTER TABLE recoveryPoints ADD FOREIGN KEY(child) REFERENCES runs(runId);
          ALTER TABLE syncWork ADD FOREIGN KEY(child) REFERENCES runs(runId), ADD FOREIGN KEY(scope) REFERENCES syncScopes(scope);
          CREATE TABLE ledger_version(version integer PRIMARY KEY);
          INSERT INTO ledger_version VALUES(1);`,
          ),
        );
        this.raw(
          'CREATE TABLE IF NOT EXISTS leases(id text PRIMARY KEY REFERENCES runs("runId"), owner text NOT NULL, generation bigint NOT NULL, expires bigint NOT NULL)',
        );
      }
      if (this.raw('SELECT version FROM ledger_version').rows[0]?.version !== 1)
        throw Error('Unsupported shared ledger version');
      this.raw(identifiers(temporaryWebhookTable.replaceAll('INTEGER', 'BIGINT')));
      this.commit();
    } catch (error) {
      this.close();
      throw error;
    }
  }
  raw(sql: string, values: Value[] = []): Result {
    if (this.#closed) throw Error('Closed PostgreSQL session');
    Atomics.store(this.#signal, 0, 0);
    this.#port.postMessage({ sql, values });
    if (Atomics.wait(this.#signal, 0, 0, 20000) === 'timed-out') {
      this.close();
      queueMicrotask(() => this.onDisconnect?.());
      throw Error('PostgreSQL unavailable; transaction outcome requires verification');
    }
    const reply = receiveMessageOnPort(this.#port)?.message as Result | undefined;
    if (!reply || reply.error) throw Error(reply?.error ?? 'PostgreSQL session failed');
    return reply;
  }
  begin() {
    this.raw('BEGIN');
    this.#transaction = true;
    try {
      this.raw('SELECT pg_advisory_xact_lock(hashtextextended($1,0))', [this.schema]);
      this.assertOwner();
    } catch (e) {
      this.rollback();
      throw e;
    }
  }
  commit() {
    this.assertOwner();
    try {
      this.raw('COMMIT');
    } finally {
      this.#transaction = false;
    }
  }
  rollback() {
    try {
      this.raw('ROLLBACK');
    } finally {
      this.#transaction = false;
    }
  }
  assertOwner() {
    const token = this.lease.getStore();
    if (
      token &&
      !this.raw('SELECT 1 FROM leases WHERE id=$1 AND owner=$2 AND generation=$3 AND expires>' + nowMs, [
        token.id,
        this.owner,
        token.generation,
      ]).rows.length
    )
      throw new OwnershipLost('Worker lease expired');
  }
  checkDispatch() {
    this.assertOwner();
  }
  atomic<T>(fn: () => T): T {
    if (this.#transaction) return fn();
    this.begin();
    try {
      const value = fn();
      this.commit();
      return value;
    } catch (e) {
      this.rollback();
      throw e;
    }
  }
  exec(sql: string) {
    if (sql === 'BEGIN IMMEDIATE') return this.begin();
    if (sql === 'COMMIT') return this.commit();
    if (sql === 'ROLLBACK') return this.rollback();
    throw Error('Unexpected ledger transaction command');
  }
  prepare(sql: string) {
    const statement = querySql(sql);
    const query = (values: Value[]) =>
      this.#transaction ? this.raw(statement, values) : this.atomic(() => this.raw(statement, values));
    // SQLite exposes rowid only by explicit projection, and predicates as 0/1.
    const read = (values: Value[]) => {
      const rows = query(values).rows;
      for (const row of rows) {
        if (/^SELECT \*/i.test(sql)) delete row.rowid;
        for (const key of Object.keys(row)) if (typeof row[key] === 'boolean') row[key] = Number(row[key]);
      }
      return rows;
    };
    return {
      all: (...v: Value[]) => read(v),
      get: (...v: Value[]) => read(v)[0],
      run: (...v: Value[]) => query(v),
    };
  }
  acquire(id: string) {
    return Number(
      this.raw(
        'INSERT INTO leases VALUES($1,$2,1,' +
          nowMs +
          '+$3::bigint) ON CONFLICT(id) DO UPDATE SET owner=excluded.owner,generation=leases.generation+1,expires=excluded.expires RETURNING generation',
        [id, this.owner, this.leaseMs],
      ).rows[0]!.generation,
    );
  }
  ownsLiveRun(id: string) {
    return !!this.raw('SELECT 1 FROM leases WHERE id=$1 AND owner=$2 AND expires>' + nowMs, [id, this.owner])
      .rows.length;
  }
  expired(id: string) {
    return !this.raw('SELECT 1 FROM leases WHERE id=$1 AND expires>' + nowMs, [id]).rows.length;
  }
  now() {
    return Number(this.raw('SELECT ' + nowMs + ' AS t').rows[0]!.t);
  }
  #target(key: string) {
    const [origin, credential] = JSON.parse(key) as [string, string | null];
    const alias =
      credential &&
      this.options.rateAccounts &&
      Object.hasOwn(this.options.rateAccounts, credential) &&
      this.options.rateAccounts[credential];
    return JSON.stringify([
      origin,
      credential === null
        ? ['anonymous']
        : alias
          ? ['account', alias]
          : ['organization', this.schema, credential],
    ]);
  }
  reserveTarget(key: string) {
    const target = this.#target(key),
      capacity = this.options.maxTargetRequests ?? 4;
    return this.atomic(() => {
      this.raw('INSERT INTO draflow_coord.targets VALUES($1,0,$2) ON CONFLICT DO NOTHING', [
        target,
        capacity,
      ]);
      const state = this.raw(
        'SELECT until_ms,capacity FROM draflow_coord.targets WHERE target=$1 FOR UPDATE',
        [target],
      ).rows[0]!;
      if (state.capacity !== capacity) throw Error('Inconsistent shared target capacity');
      const remaining = Number(state.until_ms) - this.now();
      if (remaining > 0) return { delay: remaining };
      this.raw('DELETE FROM draflow_coord.permits WHERE target=$1 AND expires<=' + nowMs, [target]);
      if (
        Number(
          this.raw('SELECT count(*) AS n FROM draflow_coord.permits WHERE target=$1', [target]).rows[0]!.n,
        ) >= capacity
      )
        return { delay: 25 };
      const token = randomUUID();
      const run = this.lease.getStore();
      if (!run) throw Error('A shared transport requires a worker lease');
      this.raw('INSERT INTO draflow_coord.permits VALUES($1,$2,$3,' + nowMs + '+$4::bigint,$5,$6)', [
        token,
        target,
        this.owner,
        this.leaseMs,
        run.id,
        run.generation,
      ]);
      return {
        delay: 0,
        release: () => {
          this.raw('DELETE FROM draflow_coord.permits WHERE token=$1 AND owner=$2', [token, this.owner]);
        },
      };
    });
  }
  holdTarget(key: string, until: number) {
    this.atomic(() =>
      this.raw(
        'INSERT INTO draflow_coord.targets(target,until_ms,capacity) VALUES($1,$2,$3) ' +
          'ON CONFLICT(target) DO UPDATE SET until_ms=greatest(targets.until_ms,excluded.until_ms)',
        [this.#target(key), until, this.options.maxTargetRequests ?? 4],
      ),
    );
  }
  heartbeat() {
    this.atomic(() => {
      this.raw(
        'UPDATE draflow_coord.permits SET expires=' +
          nowMs +
          '+$2::bigint WHERE owner=$1 AND expires>' +
          nowMs +
          ' AND EXISTS(SELECT 1 FROM leases l WHERE l.id=permits.run_id AND l.generation=permits.generation AND l.owner=permits.owner AND l.expires>' +
          nowMs +
          ')',
        [this.owner, this.leaseMs],
      );
      this.raw(
        'UPDATE leases SET expires=' +
          nowMs +
          '+$2::bigint WHERE owner=$1 AND expires>' +
          nowMs +
          ' AND id IN (SELECT "runId" FROM runs WHERE state=\'running\')',
        [this.owner, this.leaseMs],
      );
    });
  }
  close() {
    this.#closed = true;
    this.#port.close();
    void this.#worker.terminate();
  }
}
